const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
// Exercise the real Vue/Pinia stores without starting Wails; only the desktop API is stubbed.
const root = require('node:path').resolve(__dirname, '../..');
const localRequire = Module.createRequire(root + '/vue/package.json');
const ts = localRequire('typescript');
Module._extensions['.ts'] = (mod, file) => mod._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020}}).outputText, file);
const apiPath = root + '/vue/src/api.ts';
require.cache[apiPath] = {id:apiPath, filename:apiPath, loaded:true, exports:{api:{},recordClientError:async()=>{},acknowledgeReminder:async()=>{}}};
const {createPinia,setActivePinia} = localRequire('pinia');
setActivePinia(createPinia());
const {useAppStore} = require(root+'/vue/src/stores/app.ts');
const {usePlansStore} = require(root+'/vue/src/stores/plans.ts');
const {useSessionsStore} = require(root+'/vue/src/stores/sessions.ts');
const {useActiveLearning} = require(root+'/vue/src/features/sessions/useActiveLearning.ts');
const {useTodayView} = require(root+'/vue/src/features/today/useTodayView.ts');
const app = useAppStore(), plans = usePlansStore(), sessions = useSessionsStore();
const plan = {id:1,subjectId:1,subject:'QA',startTime:'16:00',duration:60,breakMinutes:10,weekdays:'0,1,2,3,4,5,6',active:true};
plans.setPlans([plan]);
const base = new Date(2026,10,17,16,47,40).getTime();
app.now=base;
const learning=useActiveLearning(), today=useTodayView();
assert.equal(today.unstartedPlanRemainingSeconds.value,740);
const session={id:1,planId:1,subjectId:1,subject:'QA',startAt:new Date(base).toISOString(),plannedEndAt:new Date(2026,10,17,17).toISOString(),duration:0,endAt:null,pausedAt:null};
sessions.liveSession=session;
assert.equal(learning.countdownLeft.value,740);
assert.equal(today.unstartedPlanRemainingSeconds.value,null);
app.now=base+1500;
assert.equal(learning.countdownLeft.value,738);
app.now=base+5000;
sessions.liveSession={...session,pausedAt:new Date(app.now).toISOString(),duration:5};
app.now=base+35000;
assert.equal(learning.countdownLeft.value,705);
assert.equal(sessions.sessionSeconds(sessions.active),5);
sessions.liveSession={...session,resumedAt:new Date(app.now).toISOString(),duration:5};
app.now=base+40000;
assert.equal(learning.countdownLeft.value,700);
assert.equal(sessions.sessionSeconds(sessions.active),10);
app.now=base+340000; // skipped updates / suspended rendering
assert.equal(learning.countdownLeft.value,400);
sessions.sessions=[{...session,endAt:new Date(app.now).toISOString(),duration:610}];
sessions.liveSession=null;
assert.equal(today.unstartedPlanRemainingSeconds.value,400);
sessions.liveSession={...session,plannedEndAt:null};
assert.equal(learning.countdownLeft.value,400); // historical session boundary
app.now=new Date(2026,10,17,17).getTime();
assert.equal(learning.countdownLeft.value,0);
assert.equal(learning.countdownPercent.value,100);
sessions.liveSession={...session,startAt:new Date(2026,10,17,16,59,45).toISOString()};
app.now=new Date(2026,10,17,16,59,45).getTime();
assert.equal(learning.countdownLeft.value,15);
assert.equal(learning.countdownPercent.value,0);
console.log('PASS: second precision, start, pause, resume, skipped updates, stop with history, legacy boundary, expiry, sub-minute start');
